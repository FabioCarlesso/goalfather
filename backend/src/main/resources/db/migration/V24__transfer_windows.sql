-- Janelas de transferência e registros de jogador (issue #137).
-- Compatível com H2 (MODE=PostgreSQL) e Postgres.

-- As janelas do save, por federação (o trigrama do país: BRA = CBF). Gravadas
-- com o mundo novo, a partir do `calendar/{ano}.json` do pack, como o catálogo
-- de competições: mudar o pack não mexe num jogo em andamento. Um save anterior
-- a esta migration ganha as janelas do pack no boot (`DataInitializer`).
-- `scope` é o enum `TransferWindowScope` como texto (DOMESTIC_ONLY | INTERNATIONAL).
CREATE TABLE transfer_windows (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country    VARCHAR(3)  NOT NULL,
    start_date DATE        NOT NULL,
    end_date   DATE        NOT NULL,
    scope      VARCHAR(16) NOT NULL
);

CREATE INDEX ix_transfer_windows_country ON transfer_windows(country);

-- Um registro por vez que um jogador entra num clube (compra no mercado ou
-- proposta aceita), na data do relógio do jogo. Conta o limite de "1 por
-- janela, 2 por temporada". Sem FK em `player_id`, pelo motivo da
-- `transfer_offers`: aposentado é apagado de `players`, o histórico fica.
CREATE TABLE player_registrations (
    id            BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id     BIGINT  NOT NULL,
    club_id       BIGINT  NOT NULL,
    registered_on DATE    NOT NULL
);

CREATE INDEX ix_player_registrations_player ON player_registrations(player_id);
