-- Propostas de transferência entre técnicos humanos (issue #63).
-- Compatível com H2 (MODE=PostgreSQL) e Postgres.

-- Uma linha por proposta, do envio até um estado terminal — que nunca mais
-- muda. `status` é a máquina de estados do domínio (`OfferStatus`) como texto,
-- e `expiry_reason` só é preenchido em EXPIRED; o mapper reconstrói o `sealed`.
--
-- Toda transição é um UPDATE condicional `... WHERE status = 'PENDING'`: duas
-- escritas que partiram da mesma leitura (aceite × recusa, aceite × prazo
-- vencendo) não valem ambas — por isso não há coluna `version` aqui.
--
-- Os nomes são uma FOTO do momento da proposta, como os da `rounds.matches_json`:
-- o histórico segue legível depois que o jogador muda de clube ou se aposenta.
-- Pelo mesmo motivo `player_id` não tem FK: aposentado é APAGADO de `players`
-- (issue #55), e a proposta que o envolveu continua existindo.
CREATE TABLE transfer_offers (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_club_id    BIGINT       NOT NULL REFERENCES clubs(id),
    buyer_club_name  VARCHAR(120) NOT NULL,
    seller_club_id   BIGINT       NOT NULL REFERENCES clubs(id),
    seller_club_name VARCHAR(120) NOT NULL,
    player_id        BIGINT       NOT NULL,
    player_name      VARCHAR(120) NOT NULL,
    amount           BIGINT       NOT NULL,
    rounds_left      INTEGER      NOT NULL,
    status           VARCHAR(16)  NOT NULL,
    expiry_reason    VARCHAR(24)
);

-- Leituras do caminho quente: as propostas de um clube (Dashboard, polling) e
-- as pendentes de um jogador (rivais expiradas no aceite).
CREATE INDEX ix_transfer_offers_buyer  ON transfer_offers(buyer_club_id);
CREATE INDEX ix_transfer_offers_seller ON transfer_offers(seller_club_id);
CREATE INDEX ix_transfer_offers_player_status ON transfer_offers(player_id, status);
